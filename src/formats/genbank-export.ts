import { renderLocation } from '../domain/locations';
import { type Feature, type Qualifier, type SequenceDocument, validateDocument } from '../domain/model';

export type GenBankExport = { text: string; filename: string; warnings: string[]; exportedFeatures: number };
const UNQUOTED = new Set(['codon_start', 'transl_table', 'citation', 'compare', 'direction', 'estimated_length', 'rpt_type', 'rpt_unit_range', 'transl_except']);
function normalized(text: string): string {
  if (/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/.test(text)) throw new Error("Control character cannot be exported to GenBank.");
  return text.replace(/\s+/g, ' ').trim();
}
function wrap(text: string, width: number): string[] {
  // Never split a word in free text: that would insert a space in its value on reimport.
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(' ')) {
    if (line && line.length + word.length + 1 > width) { lines.push(line); line = word; }
    else line += (line ? ' ' : '') + word;
  }
  lines.push(line);
  return lines;
}
function header(key: string, text: string): string[] {
  return wrap(text, 67).map((line, i) => (i ? ' '.repeat(12) : key.padEnd(12)) + line);
}
function location(feature: Feature): string { return feature.unresolved?.expression ?? renderLocation(feature.segments, feature.strand); }
function qualifier(q: Qualifier): string[] {
  if (q.key.length > 20) throw new Error(`Key “${q.key}” is too long for this GenBank export (20 characters).`);
  const prefix = '/' + q.key;
  if (q.value === null) return [' '.repeat(21) + prefix];
  let value = normalized(q.value), rendered: string;
  if (q.key === 'translation') value = value.replace(/\s/g, '');
  if (UNQUOTED.has(q.key)) {
    if (!value || /[\s"\r\n]/.test(value)) throw new Error(`Unquoted value “${q.key}” cannot be exported without modification.`);
    rendered = `${prefix}=${value}`;
  } else rendered = `${prefix}="${value.replace(/"/g, '""')}"`;
  const lines = q.key === 'translation' ? rendered.match(/.{1,58}/g)! : wrap(rendered, 58);
  return lines.map(line => ' '.repeat(21) + line);
}
/** Interchange export of the current supported model, not a lossless native save
 * or an INSDC database submission validator. Never copies an old accession/date.
 */
export function exportGenBank(input: SequenceDocument, date = new Date()): GenBankExport {
  const doc = validateDocument(input);
  if (!doc.sequence.length) throw new Error("The document has no sequence. Save .sg.json, or paste DNA before interchange export.");
  if (!Number.isFinite(date.getTime())) throw new Error("Invalid export date.");
  const name = doc.name.replace(/[^A-Za-z0-9_.-]/g, '_').slice(0, 16) || 'sequence';
  const dateText = `${String(date.getUTCDate()).padStart(2, '0')}-${['JAN','FEB','MAR','APR','MAY','JUN','JUL','AUG','SEP','OCT','NOV','DEC'][date.getUTCMonth()]}-${date.getUTCFullYear()}`;
  const warnings = ["Interchange export of the current document: the native .sg.json format is still required to preserve all data.",
    "Internal identifiers, history, original archive and archived qualifiers are not included. Old accessions/references are not reassigned.",
    "Colours and names use interchange qualifiers (label, ApEinfo_fwdcolor) that some programs may ignore. This file is not validated for INSDC submission."];
  if (doc.creation) warnings.push('Structured PCR creation inputs, template snapshot, content hashes and transfer report are not retained by this exchange format. Save .sg.json or export the creation record separately.');
  if (name !== doc.name) warnings.push(`LOCUS name simplified to “${name}” (maximum 16 ASCII characters).`);
  if (doc.primers.length) warnings.push(`${doc.primers.length} library oligo(s) and the saved PCR recipe are not exported: GenBank primer_bind features do not encode the full oligo library. Keep the native file or export primer FASTA.`);
  if (doc.features.some(f => f.unresolved)) warnings.push('Unresolved location descriptors are exported as declared; remote sequences and uncertain endpoints are not validated or resolved.');
  const unoriented = doc.features.filter(f => f.strand === 0).length;
  if (unoriented) warnings.push(`${unoriented} unstranded feature(s) exported without complement; unstranded status is indicated by a note, not preserved as a separate strand value.`);
  const modified = doc.features.filter(f => f.reviewRequired).length;
  if (modified) warnings.push(`${modified} feature(s) requiring review: warning retained in /note, not as an editable status.`);
  let whitespace = normalized(doc.description) !== doc.description;
  const lines = [`LOCUS       ${name.padEnd(16)} ${String(doc.sequence.length).padStart(11)} bp    DNA     ${doc.topology.padEnd(8)} SYN ${dateText}`,
    ...header('DEFINITION', normalized(doc.description) || '.'), 'ACCESSION   .', 'VERSION     .', 'KEYWORDS    .',
    ...header('COMMENT', `Generated by Gin Schnaps 0.8.7. Current edited sequence; no original accession implied. Display name: ${normalized(doc.name)}.`),
    ...header('COMMENT', 'Interchange export only. Keep the native .sg.json for source archives, history and review state.'),
    'FEATURES             Location/Qualifiers'];
  for (const feature of doc.features) {
    if (!/^[A-Za-z][A-Za-z0-9_'*-]{0,14}$/.test(feature.type))
      throw new Error(`Type « ${feature.type}” cannot be exported: use a GenBank key of at most 15 characters, without spaces.`);
    lines.push('     ' + feature.type.padEnd(16) + location(feature));
    const quals = [...feature.qualifiers];
    if (quals.find(q => q.key === 'label')?.value !== feature.name) quals.unshift({ key: 'label', value: feature.name });
    if (quals.find(q => q.key === 'ApEinfo_fwdcolor')?.value !== feature.color) quals.unshift({ key: 'ApEinfo_fwdcolor', value: feature.color });
    if (feature.strand === 0) quals.push({ key: 'note', value: 'Gin Schnaps: this feature had no strand orientation in the native document.' });
    if (feature.reviewRequired) quals.push({ key: 'note', value: 'Gin Schnaps: annotation requires review after editing; no biological validation implied.' });
    if (quals.length > 200) throw new Error(`Too many qualifiers after conversion for “${feature.name}” (reimport limit: 200).`);
    for (const q of quals) {
      if (q.value !== null && normalized(q.value) !== q.value) whitespace = true;
      lines.push(...qualifier(q));
    }
  }
  lines.push('ORIGIN');
  for (let i = 0; i < doc.sequence.length; i += 60)
    lines.push(String(i + 1).padStart(9) + ' ' + doc.sequence.slice(i, i + 60).toLowerCase().match(/.{1,10}/g)!.join(' '));
  lines.push('//');
  if (lines.some(line => /[^\x00-\x7f]/.test(line))) warnings.push("Unicode text written in UTF-8; compatibility with ASCII-only readers is not guaranteed.");
  if (whitespace) warnings.push("Repeated spaces, tabs and line breaks normalized in text fields.");
  if (lines.some(line => line.length > 80)) warnings.push("Some values without spaces exceed 80 columns to avoid changing words: compatibility with strict readers is not guaranteed.");
  const text = lines.join('\n') + '\n';
  if (new TextEncoder().encode(text).length > 2_000_000) throw new Error("GenBank export exceeds the 2 MB reimport limit.");
  return { text, filename: name + '.gb', warnings, exportedFeatures: doc.features.length };
}
