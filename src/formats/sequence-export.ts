import { selectedSequence, toUserRange, validateDocument, type Selection, type SequenceDocument } from '../domain/model';
import { exportGenBank } from './genbank-export';

export type SequenceFormat = 'genbank' | 'embl' | 'fasta' | 'text' | 'oligo-fasta';
export type SequenceExport = { text: string; filename: string; warnings: string[]; exportedFeatures: number };
export const SEQUENCE_FORMATS: { id: SequenceFormat; label: string; extension: string }[] = [
  { id: 'genbank', label: 'GenBank', extension: '.gb' },
  { id: 'embl', label: 'EMBL', extension: '.embl' },
  { id: 'fasta', label: 'FASTA', extension: '.fasta' },
  { id: 'text', label: 'Plain DNA', extension: '.txt' },
  { id: 'oligo-fasta', label: 'Oligo FASTA', extension: '.fasta' }
];
function lines(sequence: string): string { return sequence.match(/.{1,60}/g)!.join('\n'); }
function stem(name: string): string { return name.replace(/[^a-zA-Z0-9._-]/g, '_').slice(0,100) || 'sequence'; }
function oneLine(value: string): string { return value.replace(/[\x00-\x1f\x7f\s]+/g, ' ').trim(); }
/** EMBL uses the same INSDC feature table as GenBank. Reuse the reviewed location
 * and qualifier writer; never independently reinvent join/strand conventions.
 * Local interchange files, not accession-bearing database submissions. */
export function exportEMBL(doc: SequenceDocument, date?: Date): SequenceExport {
  const gb = exportGenBank(doc, date);
  const source = gb.text.trimEnd().split('\n');
  const start = source.findIndex(line => line.startsWith('FEATURES'));
  const end = source.findIndex(line => line === 'ORIGIN');
  if (start < 0 || end <= start) throw new Error('Cannot convert the feature table.');
  const id = gb.filename.slice(0,-3);
  const counts = { A:0, C:0, G:0, T:0, other:0 };
  for (const base of doc.sequence) {
    if (base === 'A' || base === 'C' || base === 'G' || base === 'T') counts[base]++;
    else counts.other++;
  }
  const out = [`ID   ${id}; SV 1; ${doc.topology}; DNA; STD; SYN; ${doc.sequence.length} BP.`,
    'XX', `AC   ${id};`, 'XX', `DE   ${oneLine(doc.description) || oneLine(doc.name)}`, 'XX',
    'CC   Generated by Gin Schnaps. Local identifiers, not database accessions.',
    'CC   Keep .sg.json to retain the complete native document.', 'XX',
    'FH   Key             Location/Qualifiers', 'FH',
    ...source.slice(start+1,end).map(line => 'FT' + line.slice(2)), 'XX',
    `SQ   Sequence ${doc.sequence.length} BP; ${counts.A} A; ${counts.C} C; ${counts.G} G; ${counts.T} T; ${counts.other} other;`];
  for (let i=0;i<doc.sequence.length;i+=60) {
    const grouped = doc.sequence.slice(i,i+60).toLowerCase().match(/.{1,10}/g)!.join(' ');
    out.push('     ' + grouped.padEnd(66) + String(Math.min(i+60,doc.sequence.length)).padStart(9));
  }
  out.push('//');
  const text = out.join('\n')+'\n';
  if (new TextEncoder().encode(text).length > 2_000_000) throw new Error('EMBL export exceeds 2 MB. Use the native format.');
  return { text, filename:id+'.embl', exportedFeatures:gb.exportedFeatures,
    warnings:[...gb.warnings.map(w => w.replace(/GenBank/g,'EMBL').replace(/LOCUS/g,'ID')),
      'ID/AC are local identifiers. This is not an ENA submission or an assigned accession.'] };
}
export function exportSequenceFile(input: SequenceDocument, format: SequenceFormat, selection: Selection = null): SequenceExport {
  const doc = validateDocument(input);
  if (format === 'genbank') return exportGenBank(doc);
  if (format === 'embl') return exportEMBL(doc);
  if (format === 'oligo-fasta') {
    if (!doc.primers.length) throw new Error('No saved oligos to export.');
    const text=doc.primers.map((p,i)=>`>${stem(p.name)}_${i+1} ${oneLine(p.name)}\n${lines(p.sequence)}\n`).join('');
    return {text,filename:stem(doc.name)+'-oligos.fasta',exportedFeatures:0,
      warnings:['Full oligo sequences, 5′→3′. Notes, hybridization sites and PCR setup are not included.', ...(doc.creation ? ['The structured PCR creation record is not included. Keep .sg.json.'] : [])]};
  }
  if (!doc.sequence.length) throw new Error('The document has no sequence. Save .sg.json, or paste DNA before interchange export.');
  const sequence=selection ? selectedSequence(doc,selection) : doc.sequence;
  const range=toUserRange(selection,doc.sequence.length);
  const suffix=range?`-${range.start}-${range.end}`:'';
  const name=stem(doc.name)+suffix;
  const warnings=['Bases only. Features, topology, oligos and history are not encoded.'];
  if(doc.creation)warnings.push('The structured PCR creation record is not included. Keep .sg.json or export the creation record.');
  if(selection)warnings.push('Selected bases in reference-strand order, including any origin crossing.');
  if(format==='text')return {text:sequence+'\n',filename:name+'.txt',warnings,exportedFeatures:0};
  if(format!=='fasta')throw new Error('Unsupported export format.');
  const text=`>${name} ${oneLine(doc.name)}${range?` | selected ${range.start}..${range.end}`:''}\n${lines(sequence)}\n`;
  return {text,filename:name+'.fasta',warnings,exportedFeatures:0};
}
